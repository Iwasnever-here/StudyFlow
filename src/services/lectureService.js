export const updateLectureCompletion = async ({
  supabase,
  userId,
  lectureId,
  completed,
}) => {
  const { data, error } = await supabase
    .from('lectures')
    .update({
      completed,
      completed_at: completed
        ? new Date().toISOString()
        : null,
    })
    .eq('id', lectureId)
    .eq('user_id', userId)
    .select(LECTURE_FIELDS)
    .single()

  throwIfError(error)
  return data
}

